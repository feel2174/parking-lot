// 지역 상세페이지 FAQ의 단일 소스. 화면 아코디언(RegionGuide)과 FAQPage JSON-LD
// (jsonld.ts)가 이 함수를 공유해, 렌더 텍스트와 구조화 데이터가 절대 어긋나지
// 않게 한다(Google FAQPage 정책: 스키마 문구는 화면에 보이는 콘텐츠와 일치해야 함).
export interface RegionFaq {
  q: string;
  a: string;
}

export function buildRegionFaqs({
  sigungu,
  hasResident,
}: {
  sigungu: string;
  hasResident: boolean;
}): RegionFaq[] {
  const faqs: RegionFaq[] = [];

  faqs.push({
    q: "주차장 위치와 요금은 어디서 확인하나요?",
    a: "위 목록에서 동네를 펼치면 주차장별 도로명주소, 운영 요일, 기본·추가 요금이 표시됩니다. 각 항목의 “네이버지도에서 보기”를 누르면 실제 위치와 경로를 지도로 확인할 수 있습니다. 요금·운영시간은 현장 사정에 따라 달라질 수 있으니 방문 전 관리기관에 다시 확인하는 것을 권합니다.",
  });

  if (hasResident) {
    faqs.push({
      q: "거주자우선주차구역은 어떻게 신청하나요?",
      a: `거주자우선주차구역은 누구나 바로 이용하는 곳이 아니라, 해당 지역 거주자가 신청해 배정받는 주차 구역입니다. ${sigungu}의 각 구역 카드에 정기 접수기간, 신청방법, 필요 서류, 관리기관 연락처가 정리되어 있으니 신청 전 확인하세요. 접수 일정과 요금은 관할 자치단체 공지에 따라 바뀔 수 있으므로 관리기관에 문의해 최신 정보를 확인하는 것이 가장 정확합니다.`,
    });
  }

  faqs.push({
    q: "장애인 전용 주차구역이 있는 주차장만 보고 싶어요.",
    a: "장애인 전용 주차구역을 갖춘 주차장에는 목록에서 “장애인전용구역 있음” 표시가 붙습니다. 위 검색창에 동 이름이나 주차장 이름을 입력해 원하는 위치를 빠르게 찾을 수 있습니다.",
  });

  faqs.push({
    q: "이 정보의 출처와 기준은 무엇인가요?",
    a: "본 페이지는 공공데이터포털의 전국주차장정보표준데이터와 전국거주자우선주차정보표준데이터를 지역별로 정리해 보여주는 참고용 서비스입니다. 원본 데이터의 등록·수정 시점에 따라 실제 현황과 차이가 있을 수 있으며, 정확한 요금과 신청 절차는 관할 지방자치단체 또는 관리기관 공지를 통해 확인해 주세요.",
  });

  return faqs;
}
